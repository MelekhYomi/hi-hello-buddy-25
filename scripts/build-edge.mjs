// Bundles the server functions and server routes into one Supabase Edge Function:
//   node scripts/build-edge.mjs   ->   supabase/functions/api/index.ts
// Then deploy:  npx supabase functions deploy api --no-verify-jwt --project-ref <ref>
import { build } from "esbuild";
import { readFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const shim = (f) => resolve(root, "scripts/edge", f);
const BUILTINS = /^(crypto|buffer|stream|util|events|path|fs|os|url|zlib|http|https|net|tls|assert|querystring|async_hooks|string_decoder|process|module)$/;

mkdirSync(resolve(root, "supabase/functions/api"), { recursive: true });

await build({
  entryPoints: [shim("entry.ts")],
  outfile: resolve(root, "supabase/functions/api/index.ts"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "es2022",
  legalComments: "none",
  // package.json says "sideEffects": false, but these modules register themselves on import.
  ignoreAnnotations: true,
  logLevel: "info",
  define: { "import.meta.env": "{}" },
  banner: {
    js: [
      "// @ts-nocheck  (generated by scripts/build-edge.mjs, do not edit)",
      'import { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);',
    ].join("\n"),
  },
  alias: {
    "@tanstack/react-start/server": shim("shim-server.ts"),
    "@tanstack/react-start": shim("shim-start.ts"),
    "@tanstack/react-router": shim("shim-router.ts"),
  },
  plugins: [
    {
      name: "edge-node-builtins-and-names",
      setup(b) {
        // Deno wants the node: prefix on built-in modules.
        b.onResolve({ filter: BUILTINS }, (a) => ({ path: "node:" + a.path, external: true }));
        // Give every server function its name (createServerFn -> createServerFn.named("name")).
        b.onLoad({ filter: /[\\/]src[\\/]lib[\\/][^\\/]+\.functions\.ts$/ }, (a) => ({
          contents: readFileSync(a.path, "utf8").replace(
            /export const (\w+) = createServerFn\(/g,
            'export const $1 = createServerFn.named("$1")(',
          ),
          loader: "ts",
        }));
      },
    },
  ],
});
